def openssl_sha256(path: Path) -> str:
    openssl = "/usr/bin/openssl" if os.path.isfile("/usr/bin/openssl") else "openssl"
    completed = subprocess.run(
        [openssl, "dgst", "-sha256", str(path)],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
        text=True,
    )
    digest = completed.stdout.strip().split("=", 1)[1].strip().lower()
    return "sha256:" + digest


def git_text(root: Path, *args: str) -> str:
    return subprocess.check_output(["git", "-C", str(root), *args], text=True).strip()


def copy_subject(dest: Path) -> dict[str, Path]:
    if SUBJECT_FIXTURES is None or SUBJECT_VERIFICATION is None or SUBJECT_COMPOSITION_A is None or SUBJECT_COMPOSITION_B is None:
        raise RuntimeError("CAL_FIXTURE_BOUND_SUBJECT is required for behavioral tests")
    dest.mkdir(parents=True, exist_ok=True)
    fixtures = dest / "frozen-fixtures"
    shutil.copytree(SUBJECT_FIXTURES, fixtures, copy_function=shutil.copy)
    verification = dest / "verification.json"
    composition_a = dest / "composition-a.json"
    composition_b = dest / "composition-b.json"
    shutil.copy(SUBJECT_VERIFICATION, verification)
    shutil.copy(SUBJECT_COMPOSITION_A, composition_a)
    shutil.copy(SUBJECT_COMPOSITION_B, composition_b)
    os.chmod(verification, 0o644)
    os.chmod(composition_a, 0o644)
    os.chmod(composition_b, 0o644)
    for path in [fixtures, *sorted(fixtures.rglob("*"), key=lambda item: len(item.parts))]:
        os.chmod(path, 0o755 if path.is_dir() else 0o644)
    return {
        "fixtures": fixtures,
        "manifest": fixtures / "FIXTURE_MANIFEST.json",
        "verification": verification,
        "composition_a": composition_a,
        "composition_b": composition_b,
    }


def clone_repo(dest: Path) -> Path:
    subprocess.run(
        ["git", "clone", "--local", str(REPO_ROOT), str(dest)],
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    return dest


def run_gate(
    *,
    apparatus_root: Path,
    fixture_root: Path,
    recovery_manifest: Path,
    verification_receipt: Path,
    composition_results: list[Path],
    output_path: Path,
    source_commit: str | None = None,
) -> subprocess.CompletedProcess[str]:
    if output_path.exists():
        output_path.unlink()
    command = [
        "python3",
        str(GATE),
        "--apparatus-root",
        str(apparatus_root),
        "--apparatus-source-commit",
        source_commit or git_text(apparatus_root, "rev-parse", "HEAD"),
        "--fixture-root",
        str(fixture_root),
        "--recovery-manifest",
        str(recovery_manifest),
        "--verification-receipt",
        str(verification_receipt),
        "--output",
        str(output_path),
    ]
    for path in composition_results:
        command.extend(["--composition-result", str(path)])
    return subprocess.run(
        command,
        cwd=str(REPO_ROOT),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )


def load_output(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def mutate_one_byte(path: Path) -> None:
    raw = bytearray(path.read_bytes())
    raw[0] = (raw[0] + 1) % 256
    path.write_bytes(bytes(raw))


class StaticSourceTests(unittest.TestCase):
    def test_gate_does_not_import_scientific_or_network_modules(self) -> None:
        tree = ast.parse(GATE.read_text(encoding="utf-8"), filename=str(GATE))
        imported: set[str] = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imported.update(alias.name.split(".")[0] for alias in node.names)
            elif isinstance(node, ast.ImportFrom) and node.module:
                imported.add(node.module.split(".")[0])
                imported.add(node.module)
        for forbidden in FORBIDDEN_IMPORTS:
            self.assertNotIn(forbidden, imported)

    def test_gate_source_does_not_import_runner_module(self) -> None:
        tree = ast.parse(GATE.read_text(encoding="utf-8"), filename=str(GATE))
        for node in ast.walk(tree):
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                rendered = ast.unparse(node)
                self.assertNotIn("reproduce_rc6", rendered)
                self.assertNotIn("receipt_preflight", rendered)

    def test_gate_pins_frozen_identities(self) -> None:
        source = GATE.read_text(encoding="utf-8")
        self.assertIn(PREREGISTRATION_COMMIT, source)
        self.assertIn(FIXTURE_AUTHORITY_BLOB, source)
        self.assertIn(RUNNER_BLOB, source)
        self.assertIn(RECEIPT_PREFLIGHT_BLOB, source)
        self.assertIn("QUALIFIED_FIXTURE_BOUND_SCIENTIFIC_SUBJECT", source)
        self.assertIn("byte_matched_to_surviving_historical_artifact", source)
        self.assertIn(
            "deterministically_reconstructed_without_preserved_historical_reference",
            source,
        )

    def test_frozen_authority_blob_matches_committed_file(self) -> None:
        blob = git_text(REPO_ROOT, "hash-object", str(AUTHORITY))
        committed = git_text(REPO_ROOT, "rev-parse", f"{PREREGISTRATION_COMMIT}:research/ers-contract-e-evaluation-provenance-20260921/fixture-bound-successor-rc0/FIXTURE_AUTHORITY.json")
        self.assertEqual(blob, FIXTURE_AUTHORITY_BLOB)
        self.assertEqual(committed, FIXTURE_AUTHORITY_BLOB)

    def test_runner_and_preflight_blobs_unchanged(self) -> None:
        self.assertEqual(git_text(REPO_ROOT, "hash-object", str(RUNNER)), RUNNER_BLOB)
        self.assertEqual(git_text(REPO_ROOT, "hash-object", str(RECEIPT_PREFLIGHT)), RECEIPT_PREFLIGHT_BLOB)


class IndependentDigestTests(unittest.TestCase):
    def test_openssl_matches_preregistered_literals(self) -> None:
        if SUBJECT_FIXTURES is None or SUBJECT_MANIFEST is None or SUBJECT_VERIFICATION is None or SUBJECT_COMPOSITION_A is None or SUBJECT_COMPOSITION_B is None:
            self.skipTest("CAL_FIXTURE_BOUND_SUBJECT is required")
        for case_id, files in EXPECTED_FILES.items():
            for relative, expected in files.items():
                path = SUBJECT_FIXTURES / case_id / relative
                self.assertEqual(openssl_sha256(path), expected, case_id + "/" + relative)
        self.assertEqual(openssl_sha256(SUBJECT_MANIFEST), EXPECTED_MANIFEST)
        self.assertEqual(openssl_sha256(SUBJECT_VERIFICATION), EXPECTED_VERIFICATION)
        self.assertEqual(openssl_sha256(SUBJECT_COMPOSITION_A), EXPECTED_COMPOSITION)
        self.assertEqual(openssl_sha256(SUBJECT_COMPOSITION_B), EXPECTED_COMPOSITION)


class FixtureBindingGateTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        if SUBJECT_FIXTURES is None or not SUBJECT_FIXTURES.is_dir():
            raise unittest.SkipTest("CAL_FIXTURE_BOUND_SUBJECT is required")
        cls.scratch = Path(tempfile.mkdtemp(prefix="fixture-binding-tests-"))
        cls.repo = clone_repo(cls.scratch / "apparatus")

    @classmethod
    def tearDownClass(cls) -> None:
        shutil.rmtree(cls.scratch, ignore_errors=True)

    def setUp(self) -> None:
        self.case_dir = Path(tempfile.mkdtemp(prefix="fixture-binding-case-", dir=self.scratch))
        self.subject = copy_subject(self.case_dir / "subject")
        self.output = self.case_dir / "receipt.json"

    def _run(self, **overrides: Path | list[Path] | str) -> subprocess.CompletedProcess[str]:
        return run_gate(
            apparatus_root=Path(overrides["apparatus_root"]) if "apparatus_root" in overrides else self.repo,
            fixture_root=Path(overrides["fixture_root"]) if "fixture_root" in overrides else self.subject["fixtures"],
            recovery_manifest=Path(overrides["recovery_manifest"]) if "recovery_manifest" in overrides else self.subject["manifest"],
            verification_receipt=Path(overrides["verification_receipt"]) if "verification_receipt" in overrides else self.subject["verification"],
            composition_results=list(overrides["composition_results"]) if "composition_results" in overrides else [self.subject["composition_a"], self.subject["composition_b"]],
            output_path=self.output,
            source_commit=str(overrides["source_commit"]) if "source_commit" in overrides else None,
        )

    def _assert_failed_closed(self, result: subprocess.CompletedProcess[str], label: str) -> dict:
        self.assertNotEqual(result.returncode, 0, label + " should fail closed\n" + result.stderr)
        receipt = load_output(self.output)
        self.assertEqual(receipt["status"], "FAIL")
        self.assertEqual(receipt["disposition"], "FIXTURE_BINDING_FAILED")
        self.assertEqual(receipt["scientific_hypothesis_result"], "NOT_RUN")
        self.assertFalse(receipt["scientific_matrix_authorized"])
        instrumentation = receipt["instrumentation"]
        self.assertEqual(instrumentation["contract_e_evaluation_calls"], 0)
        self.assertEqual(instrumentation["supervisor_process_launches"], 0)
        self.assertEqual(instrumentation["scientific_runner_imports"], 0)
        self.assertEqual(instrumentation["ers_candidate_runtime_imports"], 0)
        self.assertEqual(instrumentation["network_attempts"], 0)
        self.assertEqual(instrumentation["loaded_forbidden_modules"], [])
        return receipt

    def test_unmodified_subject_passes(self) -> None:
        result = self._run()
        self.assertEqual(result.returncode, 0, result.stderr)
        receipt = load_output(self.output)
        self.assertEqual(receipt["status"], "PASS")
        self.assertEqual(receipt["disposition"], "QUALIFIED_FIXTURE_BOUND_SCIENTIFIC_SUBJECT")
        self.assertFalse(receipt["scientific_matrix_authorized"])
        self.assertFalse(receipt["historical_authority_claim_for_reconstructed_inputs"])
        self.assertEqual(receipt["instrumentation"]["contract_e_evaluation_calls"], 0)
        self.assertEqual(receipt["instrumentation"]["supervisor_process_launches"], 0)
        self.assertEqual(receipt["instrumentation"]["scientific_runner_imports"], 0)
        self.assertEqual(receipt["instrumentation"]["network_attempts"], 0)
        for case_id, files in EXPECTED_FILES.items():
            for relative, expected in files.items():
                self.assertEqual(
                    receipt["observed_fixture_files"][case_id][relative]["sha256"],
                    expected,
                )
                self.assertEqual(
                    receipt["independent_digest"]["fixture_files"][case_id][relative],
                    expected,
                )
        self.assertEqual(receipt["recovery_identities"]["manifest_sha256"], EXPECTED_MANIFEST)
        self.assertEqual(receipt["recovery_identities"]["verification_json_sha256"], EXPECTED_VERIFICATION)
        self.assertEqual(receipt["recovery_identities"]["composition_result_sha256"], EXPECTED_COMPOSITION)
        self.assertEqual(receipt["apparatus_source"]["runner_blob"], RUNNER_BLOB)
        self.assertEqual(receipt["apparatus_source"]["receipt_preflight_blob"], RECEIPT_PREFLIGHT_BLOB)
        self.assertTrue(receipt["fixture_root"]["path_identity_preregistered"] is False)
        after = openssl_sha256(self.subject["fixtures"] / "PIPE01" / "cal" / "contract-c.json")
        self.assertEqual(after, EXPECTED_FILES["PIPE01"]["cal/contract-c.json"])

    def test_one_byte_pipe01_contract_c_fails(self) -> None:
        mutate_one_byte(self.subject["fixtures"] / "PIPE01" / "cal" / "contract-c.json")
        self._assert_failed_closed(self._run(), "PIPE01 Contract C byte mutation")

    def test_one_byte_consumer_inputs_fails(self) -> None:
        mutate_one_byte(self.subject["fixtures"] / "PIPE01" / "consumer-inputs.json")
        self._assert_failed_closed(self._run(), "consumer-inputs byte mutation")

    def test_one_byte_decision_target_fails(self) -> None:
        mutate_one_byte(self.subject["fixtures"] / "PIPE02" / "decision-target.json")
        self._assert_failed_closed(self._run(), "decision-target byte mutation")

    def test_swap_consumer_input_across_pipe_cases_fails(self) -> None:
        source = self.subject["fixtures"] / "PIPE01" / "consumer-inputs.json"
        target = self.subject["fixtures"] / "PIPE02" / "consumer-inputs.json"
        shutil.copyfile(source, target)
        self._assert_failed_closed(self._run(), "cross-case consumer-input swap")

    def test_remove_required_file_fails(self) -> None:
        (self.subject["fixtures"] / "PIPE03" / "contract-d.json").unlink()
        self._assert_failed_closed(self._run(), "missing required fixture file")

    def test_unexpected_runner_read_file_fails(self) -> None:
        extra = self.subject["fixtures"] / "PIPE01" / "consumer-output.json"
        extra.write_text("{}\n", encoding="utf-8")
        self._assert_failed_closed(self._run(), "unexpected runner-read fixture file")

    def test_alter_fixture_authority_json_fails(self) -> None:
        dirty = self.case_dir / "dirty-authority"
        clone_repo(dirty)
        authority = dirty / "research/ers-contract-e-evaluation-provenance-20260921/fixture-bound-successor-rc0/FIXTURE_AUTHORITY.json"
        mutate_one_byte(authority)
        self._assert_failed_closed(
            self._run(apparatus_root=dirty, source_commit=git_text(dirty, "rev-parse", "HEAD")),
            "altered FIXTURE_AUTHORITY.json",
        )

    def test_alter_recovery_manifest_fails(self) -> None:
        mutate_one_byte(self.subject["manifest"])
        self._assert_failed_closed(self._run(), "altered recovery manifest")

    def test_alter_verification_receipt_fails(self) -> None:
        mutate_one_byte(self.subject["verification"])
        self._assert_failed_closed(self._run(), "altered verification receipt")

    def test_different_runner_blob_fails(self) -> None:
        dirty = self.case_dir / "dirty-runner"
        clone_repo(dirty)
        runner = dirty / "research/ers-contract-e-evaluation-provenance-20260921/reproduce_rc6.py"
        runner.write_bytes(runner.read_bytes() + b"\n")
        self._assert_failed_closed(
            self._run(apparatus_root=dirty, source_commit=git_text(dirty, "rev-parse", "HEAD")),
            "different runner blob",
        )

    def test_provenance_classification_change_without_fixture_byte_change_fails(self) -> None:
        manifest_path = self.subject["manifest"]
        before_c = openssl_sha256(self.subject["fixtures"] / "PIPE01" / "cal" / "contract-c.json")
        text = manifest_path.read_text(encoding="utf-8")
        mutated = text.replace(
            "byte_matched_to_surviving_historical_artifact",
            "deterministically_reconstructed_without_preserved_historical_reference",
            1,
        )
        self.assertNotEqual(mutated, text)
        manifest_path.write_text(mutated, encoding="utf-8")
        after_c = openssl_sha256(self.subject["fixtures"] / "PIPE01" / "cal" / "contract-c.json")
        self.assertEqual(before_c, after_c)
        self._assert_failed_closed(self._run(), "provenance classification change")

    def test_relocating_fixture_directory_preserves_subject_identity(self) -> None:
        first = self._run()
        self.assertEqual(first.returncode, 0, first.stderr)
        first_receipt = load_output(self.output)
        relocated = copy_subject(self.case_dir / "relocated")
        second_output = self.case_dir / "receipt-relocated.json"
        second = run_gate(
            apparatus_root=self.repo,
            fixture_root=relocated["fixtures"],
            recovery_manifest=relocated["manifest"],
            verification_receipt=relocated["verification"],
            composition_results=[relocated["composition_a"], relocated["composition_b"]],
            output_path=second_output,
        )
        self.assertEqual(second.returncode, 0, second.stderr)
        second_receipt = load_output(second_output)
        self.assertNotEqual(first_receipt["fixture_root"]["path"], second_receipt["fixture_root"]["path"])
        self.assertEqual(first_receipt["subject_identity"], second_receipt["subject_identity"])
        self.assertEqual(first_receipt["subject"], second_receipt["subject"])
        self.assertFalse(first_receipt["fixture_root"]["path_identity_preregistered"])


